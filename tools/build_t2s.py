#!/usr/bin/env python3
"""Build data/shared/t2s.tsv: a 繁→簡 conversion table for display only.

Sources (fetched once into tools/_cache/t2s, then offline):
  OpenCC TSCharacters.txt  — single-character 繁→簡; values may list several
                             candidates separated by spaces; the first one is
                             the canonical simplified form.
  OpenCC TSPhrases.txt     — phrase rules, including identity rules such as
                             乾隆→乾隆 that shield characters whose conversion
                             would be wrong inside a word.

Additions: a hand-curated list of 異體字 present in this corpus that neither
table covers (衞→卫 and friends). Kept explicit so the provenance of every
non-OpenCC rule is visible.

Output format (UTF-8, tab separated, '#' starts a comment line):
  <source>\t<target>
Longer sources win at match time; a rule whose target equals its source is a
protection (identity) rule and is only kept for phrases.
"""

import json
import os
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, "tools/_cache/t2s")
OUT = os.path.join(ROOT, "data/shared/t2s.tsv")
BASE = "https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/"

# 異體字 that occur in this corpus and are missing from both OpenCC tables.
# Only unambiguous equivalences: names and rare 通假字 (蹻, 驩) stay untouched.
ADDENDA = {
    "衞": "卫", "旣": "既", "羣": "群", "畧": "略", "眞": "真",
    "冨": "富", "槩": "概", "畱": "留", "牀": "床", "箇": "个",
    "祕": "秘", "姦": "奸", "麤": "粗", "疋": "匹", "舘": "馆",
    "劄": "札", "煑": "煮",
}


def fetch(name):
    os.makedirs(CACHE, exist_ok=True)
    path = os.path.join(CACHE, name)
    if not os.path.exists(path) or os.path.getsize(path) < 1000:
        urllib.request.urlretrieve(BASE + name, path)
    return path


def read_rules(path, keep_identity):
    rules = {}
    for line in open(path, encoding="utf-8"):
        line = line.rstrip("\n")
        if not line or line.startswith("#"):
            continue
        parts = line.split("\t")
        if len(parts) < 2:
            continue
        src = parts[0].strip()
        dst = parts[1].split(" ")[0].strip()
        if not src or not dst:
            continue
        if src == dst and not keep_identity:
            continue
        rules[src] = dst
    return rules


def main():
    chars = read_rules(fetch("TSCharacters.txt"), keep_identity=False)
    chars = {src: dst for src, dst in chars.items() if len(src) == 1 and len(dst) == 1}
    for src, dst in ADDENDA.items():
        chars[src] = dst
    phrases = read_rules(fetch("TSPhrases.txt"), keep_identity=True)
    phrases = {src: dst for src, dst in phrases.items() if 2 <= len(src) <= 8}
    # A phrase target must not itself need conversion (no chained rules).
    phrases = {
        src: dst
        for src, dst in phrases.items()
        if not any(ch in chars for ch in dst)
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# t2s.tsv — generated by tools/build_t2s.py; do not edit by hand.\n")
        fh.write("# Format: <source>\\t<target>. Longer sources win; identity rules protect words.\n")
        fh.write("# Sources: OpenCC TSCharacters.txt + TSPhrases.txt, plus %d curated 異體字.\n" % len(ADDENDA))
        fh.write("# chars: %d, phrases: %d\n" % (len(chars), len(phrases)))
        for src in sorted(chars):
            fh.write("%s\t%s\n" % (src, chars[src]))
        for src in sorted(phrases):
            fh.write("%s\t%s\n" % (src, phrases[src]))
    print("wrote", OUT, "chars", len(chars), "phrases", len(phrases))


if __name__ == "__main__":
    main()
