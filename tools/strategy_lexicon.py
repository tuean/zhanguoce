def kinds() -> list[str]:
    """Every declared kind, in page order."""
    return [block["kind"] for block in LEXICON]


def patterns() -> list[tuple[str, str, str]]:
    """(kind, pattern, why) triples, flattened."""
    out: list[tuple[str, str, str]] = []
    for block in LEXICON:
        for entry in block["entries"]:
            out.append((block["kind"], entry["pattern"], entry["why"]))
    return out


def rationale(kind: str) -> str:
    for block in LEXICON:
        if block["kind"] == kind:
            return block["rationale"]
    raise KeyError(kind)


# 命中重疊時的裁剪規則：同一段內，按起點排序、同起點取較長者，
# 已被前一條覆蓋的命中丟棄。例如「豈不亦忠乎」既有「豈…乎」也有「不亦…乎」，
# 只留較長的「豈不亦忠乎」，避免同一句話被標兩次。
def resolve_overlaps(hits: list[tuple[int, int, str, str]]) -> list[tuple[int, int, str, str]]:
    """hits: (offset, length, kind, matched) in one paragraph → non-overlapping."""
    ordered = sorted(hits, key=lambda h: (h[0], -h[1]))
    kept: list[tuple[int, int, str, str]] = []
    last_end = -1
    for hit in ordered:
        if hit[0] <= last_end:
            continue
        kept.append(hit)
        last_end = hit[0] + hit[1] - 1
    return kept
